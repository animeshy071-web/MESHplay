// Computes CRC32 of every bundled ROM and patches src/system/romdb.ts with the
// real checksum table. Run whenever public/roms changes.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

function crc32(buf) {
  const t = new Uint32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[n] = c
  }
  let crc = 0xffffffff
  for (let i = 0; i < buf.length; i++) crc = t[(crc ^ buf[i]) & 0xff] ^ (crc >>> 8)
  return (crc ^ 0xffffffff) >>> 0
}

const romDir = join(ROOT, 'public', 'roms')
const entries = readdirSync(romDir)
  .filter((f) => f.endsWith('.ch8'))
  .map((f) => {
    const data = readFileSync(join(romDir, f))
    return { crc32: crc32(data), title: f.replace(/\.ch8$/, '').toUpperCase(), platform: 'CHIP-8' }
  })
  .sort((a, b) => a.title.localeCompare(b.title))

const body = `// Offline ROM hash database — CRC32 checksums of the bundled homebrew set.
// Format matches the libretro/OpenVGDB-style (crc32 -> title). Custom games
// scanned from disk are matched here first, then against the user's own
// SQLite library. Fully offline; online scrapers remain optional (later).
// AUTO-GENERATED by scripts/gen-romdb.mjs — do not hand-edit the table.

export interface RomDbEntry {
  crc32: number
  title: string
  platform: string
  year?: number
  author?: string
}

export const ROM_DB: RomDbEntry[] = [
${entries.map((e) => `  { crc32: 0x${e.crc32.toString(16).padStart(8, '0')}, title: '${e.title.replace(/'/g, "\\'")}', platform: '${e.platform}' },`).join('\n')}
]

/** Offline CRC32 lookup — exact match only. */
export function matchRom(crc32: number): RomDbEntry | null {
  return ROM_DB.find((e) => e.crc32 === crc32) ?? null
}
`
writeFileSync(join(ROOT, 'src', 'system', 'romdb.ts'), body)
console.log(`[romdb] ${entries.length} entries written`)
